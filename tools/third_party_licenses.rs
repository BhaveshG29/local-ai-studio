//! Generates `THIRD_PARTY_LICENSES.md` from `cargo metadata`.
//!
//! Run from the repository root (dependencies must be available locally, e.g. after a
//! normal build):
//!
//! ```text
//! cargo run --bin third-party-licenses > THIRD_PARTY_LICENSES.md
//! ```
//!
//! Every crate compiled into Local AI Studio (normal and build dependencies, for all
//! platforms) is listed with its SPDX license expression, and the license files each crate
//! ships are reproduced once (identical texts are merged). The bundled fonts' licenses are
//! included as well.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::path::{Path, PathBuf};
use std::process::Command;

use serde_json::Value;

struct Package {
    name: String,
    version: String,
    license: String,
    repository: String,
    dir: PathBuf,
}

fn main() {
    if let Err(e) = run() {
        eprintln!("error: {e}");
        std::process::exit(1);
    }
}

fn run() -> Result<(), String> {
    let out = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()))
        .args(["metadata", "--format-version", "1", "--locked"])
        .output()
        .map_err(|e| format!("could not run cargo metadata: {e}"))?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).into_owned());
    }
    let meta: Value = serde_json::from_slice(&out.stdout).map_err(|e| e.to_string())?;
    let root_id = meta["resolve"]["root"].as_str().ok_or("no root package")?.to_string();
    let workspace_root = PathBuf::from(meta["workspace_root"].as_str().unwrap_or("."));

    let mut packages: HashMap<String, Package> = HashMap::new();
    for p in meta["packages"].as_array().ok_or("no packages")? {
        let id = p["id"].as_str().unwrap_or_default().to_string();
        let manifest = PathBuf::from(p["manifest_path"].as_str().unwrap_or_default());
        packages.insert(
            id,
            Package {
                name: p["name"].as_str().unwrap_or_default().to_string(),
                version: p["version"].as_str().unwrap_or_default().to_string(),
                license: p["license"]
                    .as_str()
                    .map(str::to_string)
                    .or_else(|| p["license_file"].as_str().map(|f| format!("see {f}")))
                    .unwrap_or_else(|| "unspecified".into()),
                repository: p["repository"].as_str().unwrap_or_default().to_string(),
                dir: manifest.parent().map(Path::to_path_buf).unwrap_or_default(),
            },
        );
    }

    // Walk the dependency graph from the root, skipping dev-only edges.
    let mut edges: HashMap<String, Vec<String>> = HashMap::new();
    for node in meta["resolve"]["nodes"].as_array().ok_or("no resolve graph")? {
        let id = node["id"].as_str().unwrap_or_default().to_string();
        let mut deps = Vec::new();
        for d in node["deps"].as_array().into_iter().flatten() {
            let shipped = d["dep_kinds"]
                .as_array()
                .map(|kinds| kinds.iter().any(|k| k["kind"].as_str() != Some("dev")))
                .unwrap_or(true);
            if shipped {
                deps.push(d["pkg"].as_str().unwrap_or_default().to_string());
            }
        }
        edges.insert(id, deps);
    }
    let mut seen = BTreeSet::new();
    let mut stack = vec![root_id.clone()];
    while let Some(id) = stack.pop() {
        if !seen.insert(id.clone()) {
            continue;
        }
        stack.extend(edges.get(&id).cloned().unwrap_or_default());
    }
    seen.remove(&root_id);

    let mut crates: Vec<&Package> = seen.iter().filter_map(|id| packages.get(id)).collect();
    crates.sort_by(|a, b| a.name.cmp(&b.name).then(a.version.cmp(&b.version)));

    // Collect license texts, merging identical ones.
    let mut texts: BTreeMap<String, (String, Vec<String>)> = BTreeMap::new();
    let mut without_files = Vec::new();
    for c in &crates {
        let files = license_files(&c.dir);
        if files.is_empty() {
            without_files.push(*c);
            continue;
        }
        for f in files {
            let Ok(body) = std::fs::read_to_string(&f) else { continue };
            let key = normalise(&body);
            let label = f.file_name().map(|n| n.to_string_lossy().to_string()).unwrap_or_default();
            texts.entry(key).or_insert_with(|| (label, Vec::new())).1.push(format!("{} {}", c.name, c.version));
        }
    }

    let mut md = String::new();
    md.push_str("# Third-party licenses\n\n");
    md.push_str("Local AI Studio is licensed under the Apache License 2.0 (see `LICENSE`). It is built on the open-source components below, which keep their own licenses. This file is generated by `cargo run --bin third-party-licenses` from `Cargo.lock`; do not edit it by hand.\n\n");
    md.push_str("AI models are not part of Local AI Studio. Every model you download is owned and licensed by its publisher.\n\n");

    md.push_str("## Fonts\n\nAll bundled fonts are licensed under the SIL Open Font License 1.1.\n\n| Font | Copyright |\n|---|---|\n");
    let fonts_dir = workspace_root.join("assets/fonts/licenses");
    let mut font_files: Vec<PathBuf> = std::fs::read_dir(&fonts_dir)
        .map_err(|e| format!("{}: {e}", fonts_dir.display()))?
        .flatten()
        .map(|e| e.path())
        .collect();
    font_files.sort();
    let mut ofl_text = String::new();
    for f in &font_files {
        let body = std::fs::read_to_string(f).map_err(|e| e.to_string())?;
        let name = f.file_stem().map(|s| s.to_string_lossy().trim_end_matches("-OFL").to_string()).unwrap_or_default();
        let copyright = body.lines().find(|l| l.contains("Copyright")).unwrap_or("").trim().replace('|', "\\|");
        md.push_str(&format!("| {name} | {copyright} |\n"));
        if ofl_text.is_empty()
            && let Some(i) = body.find("This Font Software is licensed")
        {
            ofl_text = body[i..].to_string();
        }
    }
    if !ofl_text.is_empty() {
        md.push_str("\n### SIL Open Font License 1.1\n\n````text\n");
        md.push_str(ofl_text.trim_end());
        md.push_str("\n````\n\n");
    }

    md.push_str(&format!(
        "## Rust crates ({})\n\n| Crate | Version | License | Source |\n|---|---|---|---|\n",
        crates.len()
    ));
    for c in &crates {
        md.push_str(&format!(
            "| {} | {} | {} | {} |\n",
            c.name,
            c.version,
            c.license.replace('|', "\\|"),
            c.repository
        ));
    }
    if !without_files.is_empty() {
        md.push_str("\nThese crates ship no license file; their license is given by the SPDX expression above (standard texts of Apache-2.0 in `LICENSE`, others at https://spdx.org/licenses/):\n\n");
        for c in &without_files {
            md.push_str(&format!("- {} {} ({})\n", c.name, c.version, c.license));
        }
    }

    md.push_str("\n## License texts\n\n");
    for (body, (label, users)) in &texts {
        md.push_str(&format!("### {label}\n\nUsed by: {}\n\n````text\n", users.join(", ")));
        md.push_str(body.trim_end());
        md.push_str("\n````\n\n");
    }
    print!("{md}");
    Ok(())
}

/// License-like files at the top level of a crate.
fn license_files(dir: &Path) -> Vec<PathBuf> {
    let mut out: Vec<PathBuf> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_file())
        .filter(|p| {
            let n = p.file_name().map(|n| n.to_string_lossy().to_ascii_uppercase()).unwrap_or_default();
            n.starts_with("LICENSE")
                || n.starts_with("LICENCE")
                || n.starts_with("COPYING")
                || n.starts_with("NOTICE")
                || n.starts_with("UNLICENSE")
        })
        .collect();
    out.sort();
    out
}

/// Normalises line endings and trailing spaces so identical licenses are merged.
fn normalise(s: &str) -> String {
    s.replace("\r\n", "\n").lines().map(str::trim_end).collect::<Vec<_>>().join("\n").trim().to_string()
}
